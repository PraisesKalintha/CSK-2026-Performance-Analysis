    death = dube[dube['over'] >= 15]

    def phase_stats(df):
        balls = len(df[df['wide'] == 0])
        runs  = df['runs_of_bat'].sum()
        sr    = round(runs/balls*100, 1) if balls > 0 else 0
        return int(balls), int(runs), sr

    pp_b,    pp_r,    pp_sr    = phase_stats(pp)
    mid_b,   mid_r,   mid_sr   = phase_stats(mid)
    death_b, death_r, death_sr = phase_stats(death)

    total_balls = pp_b + mid_b + death_b
    total_runs  = pp_r + mid_r + death_r

