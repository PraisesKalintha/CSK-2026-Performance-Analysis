def player_analysis(player_name, label):
    print(f"\n{'─'*65}")
    print(f"{label}: {player_name}")
    print(f"{'─'*65}")

    stats = []

    for match_id in sorted(csk_match_ids):
        match_bat = csk_batting[
            csk_batting['match_id'] == match_id
        ]

        player = match_bat[
            match_bat['striker'] == player_name
        ]

        if len(player) == 0:
            continue

        entry_over = int(player['over'].iloc[0])

        balls = len(player[player['wide'] == 0])
        runs  = player['runs_of_bat'].sum()
        sr    = round(runs/balls*100, 1) if balls > 0 else 0

        fours  = len(player[player['runs_of_bat'] == 4])
        sixes  = len(player[player['runs_of_bat'] == 6])
        dots   = len(player[
            (player['runs_of_bat'] == 0) &
            (player['wide'] == 0)
        ])
        dot_pct = round(dots/balls*100, 1) if balls > 0 else 0

        dismissed = match_bat[
            match_bat['player_dismissed'] == player_name
        ]
        out_over = int(dismissed['over'].iloc[0]) \
                   if len(dismissed) > 0 else 20

        date   = match_bat['date'].iloc[0]
        result = csk_results[
            csk_results['match_id'] == match_id
        ]['result'].values[0]

        if runs >= 25 and sr >= 130:
            flag = '✅ IMPACT'
        elif balls >= 10 and sr < 100:
            flag = '⚠️  SLOW'
        elif balls <= 6 and runs <= 8:
            flag = '❌ FAILED'
        else:
            flag = ''

        stats.append({
            'date'      : date,
            'entry'     : entry_over,
            'runs'      : int(runs),
            'balls'     : balls,
            'sr'        : sr,
            'fours'     : fours,
            'sixes'     : sixes,
            'dot_pct'   : dot_pct,
            'out_over'  : out_over,
            'result'    : result,
            'flag'      : flag
        })

        print(f"{date} | "
              f"Entered: {entry_over:>2} | "
              f"{int(runs):>3} off {balls:>2} | "
              f"SR: {sr:>6} | "
              f"Dots: {dot_pct:>5}% | "
              f"4s:{fours} 6s:{sixes} | "
              f"{result} | {flag}")

    if not stats:
        print("  No innings found")
        return

    df = pd.DataFrame(stats)

    print(f"\n  SUMMARY")
    print(f"  {'─'*40}")
    print(f"  Matches          : {len(df)}")
    print(f"  Total runs       : {df['runs'].sum()}")
    print(f"  Average runs     : {df['runs'].mean():.1f}")
    print(f"  Average SR       : {df['sr'].mean():.1f}")
    print(f"  Average dot %    : {df['dot_pct'].mean():.1f}%")
    print(f"  Impact innings   : "
          f"{len(df[df['flag']=='✅ IMPACT'])}")
    print(f"  Failed innings   : "
          f"{len(df[df['flag']=='❌ FAILED'])}")
    print(f"  Slow innings     : "
          f"{len(df[df['flag']=='⚠️  SLOW'])}")

    print(f"\n  RESULTS WHEN BATTING:")
    print(f"  Wins  : "
          f"{len(df[df['result']=='WIN'])}")
    print(f"  Losses: "
          f"{len(df[df['result']=='LOSS'])}")

    return df

